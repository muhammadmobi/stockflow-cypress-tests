/**
 * GET {SW}/excel/po-numbers — the merged list under test.
 *
 * Resolves with the `poList` array. Its ELEMENT SHAPE DIFFERS BY QUERY: plain
 * strings by default, `{ name, cost }` with `cost=true`, `{ name, source }`
 * with `source=true`. Use poListNames() rather than reading elements directly.
 */
export function getStockWisePoList(swToken, { close, cost, source } = {}) {
  const params = [];
  if (close !== undefined) params.push(`close=${close}`);
  if (cost !== undefined) params.push(`cost=${cost}`);
  if (source !== undefined) params.push(`source=${source}`);
  const query = params.length ? `?${params.join('&')}` : '';

  return cy.request({
    method: 'GET',
    url: `${getStockWiseApiUrl()}/excel/po-numbers${query}`,
    headers: { Authorization: `Bearer ${swToken}` },
    failOnStatusCode: false,
    // The merged list races a 5s AccountWise call on top of a full
    // purchaseOrders scan; shared QA can be slow.
    timeout: 120000,
  }).then((resp) => {
    expect(resp.status, `GET /excel/po-numbers${query} must succeed`).to.eq(200);
    const poList = resp.body?.data?.poList;
    expect(poList, 'GET /excel/po-numbers must return data.poList as an array').to.be.an('array');
    return poList;
  });
}

/** Normalised names from a poList, shape-agnostic (see getStockWisePoList). */
export const poListNames = (poList) =>
  (poList ?? []).map((entry) => poKey(typeof entry === 'object' ? entry?.name : entry));

/** Whether a PO number is present in a poList, using StockWise's own dedup key. */
export const poListIncludes = (poList, poNumber) => poListNames(poList).includes(poKey(poNumber));

