/**
 * Every purchase order this suite creates carries this prefix in its `order_id`,
 * which is how sweepSuiteSeeds() tells our disposable seeds apart from real
 * AccountWise data. Never widen it.
 */
export const SUITE_ORDER_ID_PREFIX = 'CYP-PO-';

/**
 * Identifies the seeds created by THIS spec file's run.
 *
 * Cypress boots a fresh module registry per spec, so this is per-spec — which is
 * exactly the granularity the sweep needs: `AccountWisePoIntegrationAPI.cy.js`
 * and `AccountWisePoIntegration.cy.js` both sweep the same shared tenant, and a
 * prefix-only sweep would let either one delete the other's LIVE seeds the
 * moment the two run concurrently (Cypress parallelisation, or two engineers on
 * the same QA tenant). Ownership plus an age floor is what makes the sweep safe
 * to run at any time — see sweepSuiteSeeds().
 */
const RUN_ID = `r${Date.now().toString(36)}${Math.floor(Math.random() * 1e6).toString(36)}`;

/** `CYP-PO-<runId>-<epochMs>-<rand>` — the order_id stamped on every seed. */
export const buildSeedOrderId = () =>
  `${SUITE_ORDER_ID_PREFIX}${RUN_ID}-${Date.now()}-${Math.floor(Math.random() * 1e6)}`;

/**
 * How old ANOTHER run's seed must be before this run may delete it. Long enough
 * to outlast a full execution of either spec, short enough that a re-run later
 * in the same session still self-heals. Override with
 * `--env AWPO_SEED_MAX_AGE_MINUTES=<n>`.
 */
const getSeedSweepMinAgeMs = () =>
  Number(Cypress.env('AWPO_SEED_MAX_AGE_MINUTES') ?? 20) * 60 * 1000;

/** `{ runId, createdAt }` for one of our order_ids, or null when it is not ours. */
function parseSeedOrderId(orderId) {
  const raw = (orderId ?? '').toString();
  if (!raw.startsWith(SUITE_ORDER_ID_PREFIX)) return null;
  const parts = raw.slice(SUITE_ORDER_ID_PREFIX.length).split('-');
  // Seeds left on the tenant by a build that predates RUN_ID read
  // `<epochMs>-<rand>`. They belong to no live run, so they are always sweepable.
  const legacy = /^\d+$/.test(parts[0] ?? '');
  const createdAt = Number(legacy ? parts[0] : parts[1]);
  return {
    runId: legacy ? null : parts[0],
    createdAt: Number.isFinite(createdAt) && createdAt > 0 ? createdAt : null,
  };
}

/**
 * Delete the AccountWise purchase orders this suite has left behind, and nothing
 * else.
 *
 * Called from `before()` rather than relying on teardown, because Cypress's
 * `this.skip()` aborts a test AND its remaining hooks — `afterEach` and `after`
 * included — so a seed created just before a skip is never torn down by them.
 * Sweeping at the start makes each run self-healing regardless of how the
 * previous one ended.
 *
 * A row is deleted when it carries this suite's `order_id` prefix AND either
 *   • it belongs to THIS spec's run (`RUN_ID`) — always safe, it is ours; or
 *   • it is older than getSeedSweepMinAgeMs(), so no live run can still be
 *     asserting on it.
 * Anything else is left alone and logged, which is what keeps the sweep safe when
 * the API and UI specs run at the same time against one shared tenant.
 */
export function sweepSuiteSeeds(swToken) {
  return getAccountWisePoNumbers(swToken).then((resp) => {
    const rows = Array.isArray(resp.body?.data) ? resp.body.data : [];

    // The entire self-healing story rests on `order_id` being present in this
    // payload. If AccountWise ever stops returning it, every row parses as "not
    // ours", the sweep silently becomes a no-op, and seeds accumulate forever
    // with nothing in the log to say so. Say it out loud instead.
    if (rows.length && !rows.some((r) => r?.order_id)) {
      const warning =
        `sweepSuiteSeeds: ${rows.length} purchase order(s) came back from ` +
        `GET ${getPurchaseBaseUrl()}/purchaseOrder/numbers and NONE carries an order_id. ` +
        'Seed cleanup keys off that field, so it is now a no-op and seeds will accumulate on ' +
        'the tenant. Check whether AccountWise changed the payload shape.';
      Cypress.log({ name: 'sweepSuiteSeeds', message: warning });
      // eslint-disable-next-line no-console
      console.warn(warning);
    }

    const minAge = getSeedSweepMinAgeMs();
    const now = Date.now();
    const ours = [];
    const foreign = [];

    rows.forEach((row) => {
      const parsed = parseSeedOrderId(row?.order_id);
      if (!parsed) return;
      const isOwnRun = parsed.runId !== null && parsed.runId === RUN_ID;
      const isStale = parsed.createdAt === null || now - parsed.createdAt >= minAge;
      (isOwnRun || isStale ? ours : foreign).push(row);
    });

    if (ours.length) {
      Cypress.log({
        name: 'sweepSuiteSeeds',
        message: `Removing ${ours.length} leftover seed(s): ${ours.map((r) => r.purchase_order_number).join(', ')}`,
      });
    }
    if (foreign.length) {
      Cypress.log({
        name: 'sweepSuiteSeeds',
        message:
          `Leaving ${foreign.length} recent seed(s) from another run alone: ` +
          `${foreign.map((r) => r.purchase_order_number).join(', ')}. They are younger than ` +
          `${minAge / 60000} minute(s), so a concurrent spec may still be asserting on them.`,
      });
    }

    ours.forEach((r) => deleteAccountWisePo(swToken, r.id));
    // cy.wrap, not a bare number: cy.request commands were queued just above, so
    // returning a synchronous value here trips Cypress's mixing-async-and-sync
    // guard and fails the whole before() hook.
    return cy.wrap(ours.length, { log: false });
  });
}

/**
 * Delete a seed and THEN skip the current test.
 *
 * Cypress's `this.skip()` aborts the test and skips the remaining hooks —
 * including `afterEach` AND `after` — so a seed created before the skip is never
 * torn down. That leaked three AccountWise purchase orders per run until this
 * existed. Always clean up explicitly on the skip path; never rely on a hook.
 *
 * Call as `skipAfterCleanup.call(this, token, po, 'reason')` from a
 * `function () {}` callback, so `this` is the Mocha context.
 */
export function skipAfterCleanup(swToken, po, message) {
  const ctx = this;
  cy.log(`SKIPPED — ${message}`);
  return deleteAccountWisePo(swToken, po?.id).then(() => {
    ctx.skip();
  });
}

/**
 * Does StockWise already hold `poNumber` with status `Closed`?
 *
 * The close=false lane hard-excludes any number that is Closed in StockWise's
 * own table, REGARDLESS of what AccountWise reports. Because AccountWise
 * restarts its numbering at PO-0001 whenever its tenant is emptied, its
 * generated number frequently lands on a purchase order QA already closed — and
 * the AccountWise seed then legitimately does not appear in the open lane.
 *
 * Any TC whose subject is the open lane must check this first and skip, so the
 * environment collision is never misreported as the defect it happens to
 * resemble. (This exclusion is `SW-AWPO-API-TC11`'s own subject.)
 */
export function stockWiseHoldsClosedPo(swToken, poNumber) {
  return getStockWisePoDetail(swToken, poNumber).then((detail) => {
    const row = detail.body?.data ?? null;
    return Boolean(row?.poNumber) && row.status === 'Closed';
  });
}

/** Read a StockWise PO back by number. Raw response — 404/semantic errors are data. */
export function getStockWisePoDetail(swToken, poNumber) {
  return cy.request({
    method: 'GET',
    url: `${getStockWiseApiUrl()}/purchase-orders/po-number-detail-by-po/${encodeURIComponent(poNumber)}`,
    headers: { Authorization: `Bearer ${swToken}` },
    failOnStatusCode: false,
    timeout: 60000,
  });
}
