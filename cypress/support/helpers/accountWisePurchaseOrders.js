// cypress/support/helpers/accountWisePurchaseOrders.js
//
// Helpers for the AccountWise → StockWise PURCHASE-ORDER seam
// (cypress/qa/testPlans/purchaseOrder/AccountWisePoIntegration/plan.md).
//
// A Purchase Order raised in AccountWise has to show up in StockWise's merged
// PO list without any StockWise-side import. These helpers drive AccountWise's
// real purchase API to produce that seed, then read StockWise's merged list
// back, so a spec can assert the two systems agree.
//
// ONE TOKEN, NOT TWO — the single most important thing to get right here.
// `purchase-service` mounts the SAME IAM Keycloak guard StockWise does, so
// the StockWise bearer from cy.login() authenticates directly against it. Do
// NOT copy loginToAccountWise() from ./accountwise.js: that is for the INVOICE
// service (invoice.<host>), which still sits behind the legacy AccountWise
// identity server and needs ACCOUNTWISE_USERNAME / ACCOUNTWISE_PASSWORD. This
// module needs neither. Every parameter below is named `swToken` so a
// mismatched argument is visible at the call site.
//
// The PO NUMBER IS SERVER-GENERATED by AccountWise (generateNextDocumentNumber,
// prefix "PO"), so no caller may choose or predict it — read
// purchase_order_number out of the create response and thread it through every
// assertion.

import poFixture from '../../fixtures/accountWisePurchaseOrder.json';

// Read base URLs lazily and validate on first use, so a misconfigured run fails
// with a named env var instead of an "undefined/..." URL. Same pattern as
// requireEnv() in ./accountwise.js.
function requireEnv(name) {
  const value = Cypress.env(name);
  expect(value, `Cypress env ${name} must be configured`).to.be.a('string').and.not.empty;
  return value;
}

/** AccountWise purchase API base, including the /v1 prefix. */
export const getPurchaseBaseUrl = () => requireEnv('ACCOUNTWISE_PURCHASE_BASE_URL');

/**
 * AccountWise vendor API base. NOTE the `/api/v1` prefix — it differs from the
 * purchase and invoice services' bare `/v1`, and `purchase.<host>/v1/vendor(s)`
 * is a 404. The authoritative service map is the AccountWise SPA's own
 * `/config.json`.
 */
export const getVendorBaseUrl = () => requireEnv('ACCOUNTWISE_VENDOR_BASE_URL');

/**
 * Name of the vendor this suite raises its seed purchase orders against.
 *
 * Configured as a NAME (`ACCOUNTWISE_VENDOR_NAME`), never as a UUID: vendor ids
 * are per-tenant, so a hard-coded id is wrong on every environment except the
 * one it was captured on. Soft default so a config without the key still runs.
 */
export const getPreferredVendorName = () => Cypress.env('ACCOUNTWISE_VENDOR_NAME') || 'Test Vendor';

/** StockWise API base. */
export const getStockWiseApiUrl = () => requireEnv('API_BASE_URL');

/**
 * The dedup/compare key StockWise itself uses.
 *
 * ImportService.getPoList() keys its de-duplication Map on
 * `name.trim().toLowerCase()`, so every membership check in this module must
 * normalise the same way — otherwise a case difference between the two systems
 * reads as "the PO is missing" when it is actually present.
 */
export const poKey = (name) => (name ?? '').toString().trim().toLowerCase();

