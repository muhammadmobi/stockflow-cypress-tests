/**
 * Make sure StockWise has a counterpart row for `poNumber`, WITHOUT ever
 * mutating or deleting a purchase order this suite did not create.
 *
 * Why this is not just `createStockWisePo`: AccountWise restarts its numbering
 * (`PO-0001`, `PO-0002`, …) whenever its tenant is emptied, and shared QA's
 * StockWise already holds native purchase orders in exactly that range. So the
 * AccountWise-generated number is USUALLY already taken, and a plain create
 * returns `400 "Duplicate purchase order number detected"` — which is a fact
 * about the environment, not a defect (this is what made TC08/TC11 fail on
 * their first run).
 *
 * Resolves `{ mode, status }`:
 *   • `created` — the number was free; we made it, and the caller must delete it.
 *   • `reused`  — a StockWise row already existed with an acceptable status.
 *                 NOT registered for deletion: it is somebody else's data.
 *   • `unusable`— a row exists but its status is not the one the test needs, and
 *                 changing it would mutate shared data (closing a purchase order
 *                 also writes stockWiseStatus back into AccountWise). The caller
 *                 must this.skip() rather than force it.
 */
export function ensureStockWiseCounterpart(swToken, poNumber, { requiredStatus = null } = {}) {
  return getStockWisePoDetail(swToken, poNumber).then((detail) => {
    const row = detail.body?.data ?? null;
    const existingStatus = row?.poNumber ? row.status : null;

    if (!existingStatus) {
      return createStockWisePo(swToken, {
        poNumber,
        status: requiredStatus ?? 'Open',
      }).then(() => ({ mode: 'created', status: requiredStatus ?? 'Open' }));
    }
    if (!requiredStatus || existingStatus === requiredStatus) {
      return { mode: 'reused', status: existingStatus };
    }
    return { mode: 'unusable', status: existingStatus };
  });
}

/** Best-effort teardown of a StockWise-native PO. Never throws. */
export function deleteStockWisePo(swToken, poNumber) {
  if (!poNumber) return cy.wrap(null, { log: false });

  const del = () =>
    cy.request({
      method: 'DELETE',
      url: `${getStockWiseApiUrl()}/purchase-orders/${encodeURIComponent(poNumber)}`,
      headers: { Authorization: `Bearer ${swToken}` },
      failOnStatusCode: false,
      timeout: 60000,
    });

  return del().then((resp) => {
    if (resp.status >= 200 && resp.status < 300) return null;

    // A Closed purchase order CANNOT be deleted — PurchaseOrdersService.delete
    // throws `Cannot delete PO …: It is closed`. SW-AWPO-API-TC11 creates its
    // counterpart Closed on purpose, so without this its row would survive every
    // run, permanently occupying that number in StockWise. Since a stuck Closed
    // row is itself the "number collision" the rest of the suite has to skip
    // around, the suite would degrade its own environment run over run.
    // Reopen (the documented inverse) and retry once.
    const closed = /is closed/i.test(JSON.stringify(resp.body ?? ''));
    if (!closed) {
      Cypress.log({
        name: 'deleteStockWisePo',
        message: `Cleanup of StockWise PO ${poNumber} returned HTTP ${resp.status} — row may leak.`,
      });
      return null;
    }
    return cy.request({
      method: 'PATCH',
      url: `${getStockWiseApiUrl()}/purchase-orders/reopenPurchaseOrder`,
      headers: { Authorization: `Bearer ${swToken}` },
      body: { poNumber, status: 'Open' },
      failOnStatusCode: false,
      timeout: 60000,
    }).then(() => del()).then((retry) => {
      if (retry.status < 200 || retry.status >= 300) {
        Cypress.log({
          name: 'deleteStockWisePo',
          message: `Cleanup of StockWise PO ${poNumber} failed even after reopen (HTTP ${retry.status}) — row WILL leak and will occupy that PO number.`,
        });
      }
      return null;
    });
  });
}

