/**
 * GET {AW}/purchaseOrder/numbers — the exact call StockWise's getPoList() makes
 * server-to-server, issued here with the same bearer.
 *
 * Resolves with the raw Cypress response so callers can distinguish
 * "unreachable / rejected the token" (a suite-level skip) from "reachable but
 * the tenant is empty" (a seeding-level skip). Never throws.
 */
export function getAccountWisePoNumbers(swToken) {
  return cy.request({
    method: 'GET',
    url: `${getPurchaseBaseUrl()}/purchaseOrder/numbers`,
    headers: { Authorization: `Bearer ${swToken}` },
    failOnStatusCode: false,
    timeout: 60000,
  });
}

/**
 * Suite-level reachability probe (plan.md §8 risk 1).
 *
 * StockWise degrades SILENTLY when AccountWise is unreachable — getPoList()
 * races the call against a 5-second timeout and returns the StockWise-only list
 * on failure. Without this probe an AccountWise outage would surface as "the PO
 * is not in the list", sending the reader hunting for a filter bug that does not
 * exist. Resolves with `{ reachable, reason, rows }`.
 */
export function probeAccountWisePurchaseApi(swToken) {
  return getAccountWisePoNumbers(swToken).then((resp) => {
    if (resp.status < 200 || resp.status >= 300) {
      return {
        reachable: false,
        rows: [],
        reason:
          `AccountWise purchase API returned HTTP ${resp.status} for ` +
          `GET ${getPurchaseBaseUrl()}/purchaseOrder/numbers. ` +
          'Either the service is down or it rejected the StockWise bearer — ' +
          'this is an environment signal, not a StockWise regression.',
      };
    }
    const rows = Array.isArray(resp.body?.data) ? resp.body.data : [];
    return { reachable: true, rows, reason: null };
  });
}

/**
 * A vendor reference valid on THIS environment, scraped rather than hard-coded.
 *
 * AccountWise's createPurchaseOrderSchema requires `vendor_id` + `vendor_name`,
 * and vendor UUIDs are per-tenant — a fixture value would be wrong on every
 * environment but the one it was captured on, and a synthetic UUID is rejected
 * by the create endpoint with a **500** (an FK failure surfacing as a server
 * error), which reads as an outage rather than a bad input. So it is always
 * scraped. This mirrors getValidAccountWiseRefs() in ./accountwise.js.
 *
 * DONORS, in order:
 *   1. `GET {vendor}/vendors`, matched on `ACCOUNTWISE_VENDOR_NAME` (default
 *      "Test Vendor") — the dedicated test vendor. Preferred because it does not
 *      require a purchase order to already exist, which would otherwise be a
 *      chicken-and-egg on a fresh tenant.
 *   1b. Any other vendor on the tenant, with a loud warning. Keeps other
 *      environments runnable, but the seeds are then attached to a vendor this
 *      suite does not own.
 *   2. `GET {purchase}/purchaseOrder/numbers` — falls back to reading
 *      vendor_id/vendor_name off any existing PO, for an environment where the
 *      vendor service is unreachable but POs exist.
 *
 * Resolves `{ vendorId, vendorName }`, or **null** when neither donor yields
 * one — callers must this.skip() with a message naming the gap.
 */
export function getAccountWiseVendorRef(swToken) {
  return cy.request({
    method: 'GET',
    url: `${getVendorBaseUrl()}/vendors`,
    headers: { Authorization: `Bearer ${swToken}` },
    failOnStatusCode: false,
    timeout: 60000,
  }).then((resp) => {
    const vendors = (resp.body?.list ?? resp.body?.data?.list ?? []).filter((v) => v?.id);
    const wanted = getPreferredVendorName().trim().toLowerCase();

    // Prefer the CONFIGURED test vendor, matched by name. Taking whichever
    // vendor happens to sort first would silently raise seed purchase orders
    // against a real supplier's record the moment somebody adds a second vendor
    // to the tenant.
    const named = vendors.find((v) => (v.name ?? '').trim().toLowerCase() === wanted);
    if (named) return { vendorId: named.id, vendorName: named.name };

    if (vendors.length) {
      // Named vendor absent: fall back so other environments still run, but say
      // so loudly — the seeds are now attached to somebody else's vendor.
      Cypress.log({
        name: 'getAccountWiseVendorRef',
        message:
          `No vendor named "${getPreferredVendorName()}" on this tenant; falling back to ` +
          `"${vendors[0].name}". Create the test vendor, or set ACCOUNTWISE_VENDOR_NAME.`,
      });
      return { vendorId: vendors[0].id, vendorName: vendors[0].name ?? 'Unknown Vendor' };
    }

    // Fall back to scraping an existing purchase order.
    return probeAccountWisePurchaseApi(swToken).then(({ reachable, rows }) => {
      if (!reachable) return null;
      const donor = rows.find((r) => r?.vendor_id) ?? null;
      if (!donor) return null;
      return { vendorId: donor.vendor_id, vendorName: donor.vendor_name ?? 'Unknown Vendor' };
    });
  });
}

/**
 * Creates a Purchase Order in AccountWise and resolves with its `data` block
 * (id, purchase_order_number, total_amount, …).
 *
 * `status` selects the EP partition under test ('Pending' is the default
 * happy-path partition; 'Draft' is SW-AWPO-API-TC04's). `overrides` is merged
 * shallowly over the fixture template for negative/edge bodies.
 */
export function createAccountWisePo(swToken, { vendorRef, status = 'Pending', quantity, price, overrides = {} } = {}) {
  expect(vendorRef?.vendorId, 'createAccountWisePo needs a vendor reference — call getAccountWiseVendorRef() and skip when it is null').to.exist;

  const template = JSON.parse(JSON.stringify(poFixture.template));
  const line = poFixture.lineItem.epSingleUnit;

  const body = {
    ...template,
    // `order_id` IS REQUIRED, but AccountWise's server-side Joi schema does NOT
    // declare it — POSTing an empty body lists 13 required fields and order_id
    // is not among them. Omit it and the request is accepted by validation and
    // then dies inside the service with a bare
    // `500 {"code":"INTERNAL_SERVER_ERROR"}` and no detail. Only the SPA's own
    // client-side schema states the truth ("Order ID is required!"). This cost
    // an afternoon of probing; do not "simplify" it away.
    order_id: buildSeedOrderId(),
    vendor_id: vendorRef.vendorId,
    vendor_name: vendorRef.vendorName,
    status,
    purchase_order_date: new Date().toISOString().slice(0, 10),
    items: template.items.map((item) => ({
      ...item,
      quantity: quantity ?? line.quantity,
      price: price ?? line.price,
    })),
    ...overrides,
  };

  return cy.request({
    method: 'POST',
    url: `${getPurchaseBaseUrl()}/purchaseOrder`,
    headers: { Authorization: `Bearer ${swToken}` },
    body,
    failOnStatusCode: false,
    timeout: 60000,
  }).then((resp) => {
    expect(
      resp.status,
      `AccountWise must accept the seed purchase order (body: ${JSON.stringify(resp.body?.error ?? resp.body).slice(0, 400)})`,
    ).to.be.within(200, 299);
    const data = resp.body?.data ?? resp.body;
    expect(
      data?.purchase_order_number,
      'AccountWise must return the server-generated purchase_order_number — no test may choose it',
    ).to.exist;
    // `id` is what EVERY teardown and mutation keys off. Without this assertion a
    // renamed identifier field would make deleteAccountWisePo() short-circuit on
    // a falsy id and silently leak every seed, with no log line to notice.
    expect(
      data?.id,
      'AccountWise must return the purchase order id — teardown and every mutation key off it',
    ).to.exist;
    return data;
  });
}

/**
 * Deletes a seed PO from AccountWise (a soft delete). Best-effort and never
 * throws: a failed cleanup must not turn a passing test red, but it MUST be
 * attempted — a leaked seed permanently changes the merged list and would flip
 * the dedup (API-TC08) and sort (API-TC10) assertions on the NEXT run.
 */
export function deleteAccountWisePo(swToken, poId) {
  if (!poId) return cy.wrap(null, { log: false });
  return cy.request({
    method: 'DELETE',
    url: `${getPurchaseBaseUrl()}/purchaseOrder/${poId}`,
    headers: { Authorization: `Bearer ${swToken}` },
    failOnStatusCode: false,
    timeout: 60000,
  }).then((resp) => {
    if (resp.status < 200 || resp.status >= 300) {
      Cypress.log({
        name: 'deleteAccountWisePo',
        message: `Cleanup of AccountWise PO ${poId} returned HTTP ${resp.status} — seed may leak.`,
      });
    }
    return null;
  });
}

