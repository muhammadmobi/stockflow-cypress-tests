/** The entry for `poNumber` in a poList, shape-agnostic. Undefined when absent. */
export const poListEntry = (poList, poNumber) =>
  (poList ?? []).find(
    (entry) => poKey(typeof entry === 'object' ? entry?.name : entry) === poKey(poNumber),
  );

/** How many times `poNumber` appears — `SW-AWPO-API-TC08` asserts exactly one. */
export const poListCount = (poList, poNumber) =>
  poListNames(poList).filter((n) => n === poKey(poNumber)).length;

